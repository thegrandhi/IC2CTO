// Bundles the shared Markdown content (../content) into a TypeScript module, since
// Metro has no equivalent of Vite's import.meta.glob. Runs on install and before start.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const contentDir = join(here, '../../content');
const out = join(here, '../src/content.generated.ts');

// Coding problems need a code runner, so the iOS app leaves them to the web app.
const folders = { quiz: 'quiz', lessons: 'lessons', designs: 'design', interviews: 'interview' };

const bundle = {};
for (const [key, folder] of Object.entries(folders)) {
  bundle[key] = {};
  for (const file of readdirSync(join(contentDir, folder)).sort()) {
    if (file.endsWith('.md')) bundle[key][file.slice(0, -3)] = readFileSync(join(contentDir, folder, file), 'utf8');
  }
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/bundle-content.mjs from /content. Do not edit.\n` +
    `export const raw: Record<'quiz' | 'lessons' | 'designs' | 'interviews', Record<string, string>> = ${JSON.stringify(bundle)};\n`,
);
const counts = Object.entries(bundle).map(([k, v]) => `${Object.keys(v).length} ${k}`);
console.log(`bundle-content: ${counts.join(', ')}`);
